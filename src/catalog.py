"""Render the pricing seed from data/price_catalog.json and detect drift from the committed seed.

The catalog is the source of truth. The seed is generated from it, so a hand edit
to the seed would be silently overwritten by the next refresh. `seed_drift` renders
the seed from the catalog using the date stamped in the seed's own header and
compares the two texts exactly.
"""
from __future__ import annotations

import difflib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from config import CATALOG_PATH, SEED_PATH

HEADER_DATE = re.compile(r"^-- Generated by src/00_refresh_prices\.py on (\d{4}-\d{2}-\d{2})\.$")
REFRESH_HINT = "python src/00_refresh_prices.py --offline"


def load_catalog() -> dict:
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


def set_fetched_on(fetched_on: str) -> bool:
    """Set the catalog's top-level fetched_on in place, preserving its hand-formatted layout.

    Returns True if the file changed.
    """
    text = CATALOG_PATH.read_text(encoding="utf-8")
    updated, count = re.subn(r'("fetched_on":\s*")\d{4}-\d{2}-\d{2}(")', rf"\g<1>{fetched_on}\g<2>", text, count=1)
    if count != 1:
        raise SystemExit(f"Could not find a fetched_on date in {CATALOG_PATH.name} to update.")
    if updated == text:
        return False
    CATALOG_PATH.write_text(updated, encoding="utf-8")
    return True


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_seed(catalog: dict, fetched_on: str) -> str:
    providers = []
    for row in catalog["on_demand"]:
        if row["provider"] not in providers:
            providers.append(row["provider"])
    provider_id = {name: i + 1 for i, name in enumerate(providers)}
    model_id = {(row["provider"], row["model"]): i for i, row in enumerate(catalog["on_demand"], start=1)}
    lines = [
        f"-- Generated by src/00_refresh_prices.py on {fetched_on}.",
        "-- Edit data/price_catalog.json, then re-run the refresh. Do not hand-edit this file.",
        "",
        "INSERT INTO providers (name) VALUES",
        ",\n".join(f"({q(name)})" for name in providers) + ";",
        "",
        "INSERT INTO models (provider_id, model_name, tier) VALUES",
        ",\n".join(
            f"({provider_id[row['provider']]}, {q(row['model'])}, {q(row['tier'])})"
            for row in catalog["on_demand"]
        ) + ";",
        "",
        "INSERT INTO on_demand_pricing (model_id, input_per_mtok, output_per_mtok, effective_date, expires_date, source_url) VALUES",
        ",\n".join(
            f"({model_id[(r['provider'], r['model'])]}, {r['input_per_mtok']:.2f}, {r['output_per_mtok']:.2f}, {q(fetched_on)}, NULL, {q(r['source_url'])})"
            for r in catalog["on_demand"]
        ) + ";",
        "",
        "INSERT INTO commitment_terms (provider_id, unit_name, term, hourly_rate, note, effective_date, source_url) VALUES",
        ",\n".join(
            f"({provider_id[r['provider']]}, {q(r['unit_name'])}, {q(r['term'])}, {r['hourly_rate']:.4f}, "
            f"{q(r.get('note', ''))}, {q(fetched_on)}, {q(r['source_url'])})"
            for r in catalog["commitment_terms"]
        ) + ";",
        "",
        "INSERT INTO unit_capacity (provider_id, unit_name, model_id, burndown_tpm, output_burn, note, source_url) VALUES",
        ",\n".join(
            f"({provider_id[r['provider']]}, {q(r['unit_name'])}, {model_id[(r['provider'], r['model'])]}, "
            f"{r['burndown_tpm']}, {r['output_burn']}, {q(r.get('note', ''))}, {q(r['source_url'])})"
            for r in catalog["unit_capacity"]
        ) + ";\n",
    ]
    return "\n".join(lines)


def seed_drift(catalog: dict | None = None) -> list[str]:
    """Diff lines if the committed seed is not exactly what the catalog renders to; [] if in sync.

    In the diff, '-' lines are in the catalog's rendering but missing from the seed (catalog
    edited, seed not regenerated); '+' lines are in the seed but not the catalog (hand edit).
    """
    catalog = catalog if catalog is not None else load_catalog()
    # read_text normalizes CRLF to LF on purpose, so a Windows checkout with autocrlf is not drift.
    actual = SEED_PATH.read_text(encoding="utf-8")
    first_line = actual.splitlines()[0] if actual else ""
    match = HEADER_DATE.match(first_line)
    if not match:
        return ["seed is missing its '-- Generated by src/00_refresh_prices.py on YYYY-MM-DD.' header line"]
    expected = render_seed(catalog, match.group(1))
    if actual == expected:
        return []
    diff = difflib.unified_diff(
        expected.splitlines(), actual.splitlines(), "rendered from catalog", "committed seed", lineterm="", n=1
    )
    return list(diff) or ["seed differs from the catalog rendering only in whitespace (e.g. a missing trailing newline)"]
